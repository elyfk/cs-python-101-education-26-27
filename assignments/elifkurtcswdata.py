df = pd.read_json("musicdata.json")

df["endTime"] = pd.to_datetime(df["endTime"])
df["minutes"] = df["msPlayed"]/60000 #Orijinal spotify datasi milisaniye ile tutuluyor ancak kendi verimin spotify tarafindan islenip bana gonderilmesi 2-5 gun surebileceginden dosyayi kendim olusturdum, saniye kullanirsam gercek bir spotify datasi ile uyusmayacagindan.

df = df[df["msPlayed"] > 10000] #Atlanan sarkilari elemek icin

last_date = df["endTime"].max()
last_week = df[df["endTime"] >= last_date - pd.Timedelta(days=7)].copy()

top_artists = last_week.groupby("artistName")["minutes"].sum().sort_values(ascending=False).head(3)
